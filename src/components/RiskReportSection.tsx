import React, { useState } from 'react';
import { CycloneAnalysisResult } from '../types/cyclone';
import {
  FileText,
  Download,
  Share2,
  Send,
  Sparkles,
  Check,
  Printer,
  Copy,
  Clock,
  MapPin,
  Shield,
} from 'lucide-react';

interface RiskReportSectionProps {
  result: CycloneAnalysisResult;
  onGenerateReport?: () => void;
  isGenerating?: boolean;
}

export const RiskReportSection: React.FC<RiskReportSectionProps> = ({
  result,
  onGenerateReport,
  isGenerating = false,
}) => {
  const [copied, setCopied] = useState(false);
  const [dispatchedOps, setDispatchedOps] = useState(false);
  const [showFullPreview, setShowFullPreview] = useState(false);

  const formattedTimestamp = new Date(result.timestamp).toLocaleString('en-US', {
    timeZone: 'UTC',
    month: 'short',
    day: 'numeric',
    year: 'numeric',
    hour: '2-digit',
    minute: '2-digit',
    timeZoneName: 'short',
  });

  const generateReportText = () => {
    return `=====================================================
CYCLONESHIELD AI — OFFICIAL INCIDENT BRIEFING
BRIEFING CODE: ${result.briefingCode}
TIMESTAMP: ${result.timestamp} (${formattedTimestamp})
CLASSIFICATION: RESTRICTED // CIVIL PROTECTION OPS
=====================================================

1. TARGET & METEOROLOGICAL PARAMETERS
-------------------------------------
Location: ${result.location}
Cyclone Intensity: ${result.cycloneCategory}
Sustained Wind Speed: ${result.parameters.windSpeed} km/h
Accumulated 24h Rainfall: ${result.parameters.rainfall} mm
Peak Storm Surge: ${result.parameters.stormSurge.toFixed(1)} meters
Population Density: ${result.parameters.populationDensity}

2. HAZARD CLASSIFICATION & RISK SUMMARY
----------------------------------------
Overall Hazard Rating: ${result.overallScore}/100 [${result.overallRisk}]
Infrastructure Risk: ${result.infrastructureRiskPercent}% [${result.infrastructureRisk}]
Flood Inundation Risk: ${result.floodRiskPercent}% [${result.floodRisk}]
Transport Corridor Risk: ${result.transportRiskPercent}% [${result.transportRisk}]
Power Grid Stability Risk: ${result.powerRiskPercent}% [${result.powerRisk}]

Risk Summary:
${result.riskSummary}

Projected Civilian Impact:
${result.projectedCivilianImpact}

3. VULNERABLE INFRASTRUCTURE NODES
-----------------------------------
${result.vulnerableInfrastructure
  .map(
    (v, i) =>
      `${i + 1}. [${v.type.toUpperCase()}] ${v.name}
   Failure Probability: ${v.failProbability}% (${v.risk})
   Vulnerability: ${v.reason}
   Mitigation Directive: ${v.mitigation}`
  )
  .join('\n\n')}

4. PRIORITY ACTION AREAS
-------------------------
${result.priorityAreas
  .map(
    (p, i) =>
      `[${p.priority}] ${p.name}
   Status: ${p.status} | Action: ${p.action}
   Details: ${p.description}`
  )
  .join('\n\n')}

5. AI-GENERATED PREPAREDNESS DIRECTIVES
---------------------------------------
${result.recommendations
  .map(
    (r) =>
      `Directive #${r.id}: ${r.title} [${r.priority}]
   Action: ${r.action}`
  )
  .join('\n\n')}

=====================================================
Generated by CycloneShield AI via Google Gemini

AI Model: ${result.modelUsed}
=====================================================`;
  };

  const handleDownload = () => {
    const reportText = generateReportText();
    const blob = new Blob([reportText], { type: 'text/markdown;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.download = `CycloneShield_Briefing_${result.location.replace(/\s+/g, '_')}_${result.briefingCode}.md`;
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
    URL.revokeObjectURL(url);
  };

  const handleShare = async () => {
    const reportText = generateReportText();
    try {
      await navigator.clipboard.writeText(reportText);
      setCopied(true);
      setTimeout(() => setCopied(false), 2500);
    } catch {
      // Fallback
      alert('Report copied to clipboard');
    }
  };

  const handleDispatchOps = () => {
    setDispatchedOps(true);
    setTimeout(() => setDispatchedOps(false), 3000);
  };

  return (
    <div className="bg-[#171e37] rounded-2xl border border-[#212942] p-5 lg:p-6 shadow-xl flex flex-col gap-4">
      {/* Header */}
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-3 pb-3 border-b border-[#212942]">
        <div className="flex items-center gap-2.5">
          <div className="w-9 h-9 rounded-lg bg-orange-500/10 border border-orange-500/20 flex items-center justify-center text-orange-400">
            <FileText className="w-5 h-5" />
          </div>
          <div>
            <h2 className="font-display font-bold text-lg lg:text-xl text-white">
              Risk Report
            </h2>
            <span className="text-xs text-slate-400">
              Official disaster mitigation intelligence briefing &amp; export dispatch
            </span>
          </div>
        </div>

        <div className="flex items-center gap-2">
          <span className="px-2.5 py-1 rounded bg-[#0a122a] border border-[#2c344d] text-slate-300 font-mono-tech text-xs">
            BRIEFING: #{result.briefingCode}
          </span>
          <span className="text-xs font-mono-tech text-cyan-400 font-semibold">
            {formattedTimestamp}
          </span>
        </div>
      </div>

      {/* Briefing Summary Box */}
      <div className="bg-[#0a122a] border border-[#212942] rounded-xl p-4 flex flex-col gap-3">
        <div className="flex flex-wrap items-center justify-between gap-2">
          <div className="flex items-center gap-2">
            <MapPin className="w-4 h-4 text-cyan-400" />
            <span className="text-sm font-bold text-white">
              {result.location} · {result.cycloneCategory}
            </span>
          </div>
          <span className="text-xs font-mono-tech text-orange-400 font-semibold">
            Overall Hazard: {result.overallScore}/100 ({result.overallRisk})
          </span>
        </div>

        <p className="text-xs text-slate-300 leading-relaxed">
          Integrated hazard calculation for {result.cycloneCategory} at {result.location}.
          Synthesizes hydrodynamic surge simulations ({result.parameters.stormSurge.toFixed(1)}m),
          extreme gale vectors ({result.parameters.windSpeed} km/h), and critical substation/bridge vulnerabilities.
        </p>

        {/* 3 Core Report Highlights */}
        <div className="grid grid-cols-1 sm:grid-cols-3 gap-2 pt-2 border-t border-[#171e37] text-xs font-mono-tech">
          <div className="text-slate-400">
            <strong className="text-white block">Infrastructure Vulnerability:</strong>
            {result.infrastructureRiskPercent}% high-exposure profile
          </div>
          <div className="text-slate-400">
            <strong className="text-white block">Priority Evacuation:</strong>
            {result.priorityAreas[0]?.name || 'Sector 4 Coastal Zone'}
          </div>
          <div className="text-slate-400">
            <strong className="text-white block">Directives Active:</strong>
            {result.recommendations.length} AI incident actions generated
          </div>
        </div>
      </div>

      {/* Action Buttons Row (Prompt: "Generate AI Report", "Download Report", "Share Report") */}
      <div className="flex flex-wrap items-center justify-between gap-3 pt-2">
        <div className="flex flex-wrap items-center gap-2">
          {/* 1. Generate AI Report */}
          <button
            type="button"
            disabled={isGenerating}
            onClick={() => {
              if (onGenerateReport) onGenerateReport();
              setShowFullPreview(!showFullPreview);
            }}
            className="px-4 py-2.5 rounded-xl bg-orange-500 hover:bg-orange-600 text-white text-xs font-mono-tech font-bold flex items-center gap-2 shadow-md shadow-orange-500/20 active:scale-95 transition-all"
          >
            <Sparkles className="w-4 h-4" />
            <span>{showFullPreview ? 'Hide AI Briefing' : 'Generate AI Report'}</span>
          </button>

          {/* 2. Download Report */}
          <button
            type="button"
            onClick={handleDownload}
            className="px-4 py-2.5 rounded-xl bg-[#131a33] hover:bg-[#1c2541] border border-[#2c344d] hover:border-slate-500 text-white text-xs font-mono-tech font-bold flex items-center gap-2 active:scale-95 transition-all"
          >
            <Download className="w-4 h-4 text-cyan-400" />
            <span>Download Report (.MD)</span>
          </button>

          {/* 3. Share Report */}
          <button
            type="button"
            onClick={handleShare}
            className="px-4 py-2.5 rounded-xl bg-[#131a33] hover:bg-[#1c2541] border border-[#2c344d] hover:border-slate-500 text-white text-xs font-mono-tech font-bold flex items-center gap-2 active:scale-95 transition-all"
          >
            {copied ? (
              <>
                <Check className="w-4 h-4 text-emerald-400" />
                <span className="text-emerald-300">Copied to Clipboard!</span>
              </>
            ) : (
              <>
                <Share2 className="w-4 h-4 text-slate-300" />
                <span>Share Report</span>
              </>
            )}
          </button>
        </div>

        {/* Dispatch to Incident Ops */}
        <button
          type="button"
          onClick={handleDispatchOps}
          className={`px-4 py-2.5 rounded-xl text-xs font-mono-tech font-bold flex items-center gap-2 transition-all ${
            dispatchedOps
              ? 'bg-emerald-500 text-slate-950 shadow-md'
              : 'bg-[#131a33] text-emerald-400 border border-emerald-500/30 hover:bg-emerald-500/10'
          }`}
        >
          {dispatchedOps ? (
            <>
              <Check className="w-4 h-4" />
              <span>Transmitted to Ops Command!</span>
            </>
          ) : (
            <>
              <Send className="w-4 h-4" />
              <span>Dispatch to Incident Ops</span>
            </>
          )}
        </button>
      </div>

      {/* Full AI Report Preview Modal / Drawer */}
      {showFullPreview && (
        <div className="mt-3 p-4 bg-[#0a122a] border border-[#2c344d] rounded-xl text-xs font-mono-tech text-slate-200 overflow-x-auto whitespace-pre-wrap leading-relaxed max-h-96 overflow-y-auto">
          {generateReportText()}
        </div>
      )}
    </div>
  );
};
