import React, { useState } from 'react';
import { CycloneAnalysisResult } from '../types/cyclone';
import {
  Sparkles,
  ShieldAlert,
  Send,
  CheckCircle2,
  Clock,
  Radio,
  Zap,
  Navigation,
  Building,
  Waves,
  PhoneCall,
  Check,
} from 'lucide-react';

interface AIRecommendationsProps {
  result: CycloneAnalysisResult;
}

export const AIRecommendations: React.FC<AIRecommendationsProps> = ({ result }) => {
  const [dispatchedIds, setDispatchedIds] = useState<Record<string, boolean>>({
    '02': true,
    '04': true,
    '05': true,
  });

  const toggleDispatch = (id: string) => {
    setDispatchedIds((prev) => ({
      ...prev,
      [id]: !prev[id],
    }));
  };

  const getPriorityBadge = (priority: string) => {
    switch (priority) {
      case 'CRITICAL':
        return (
          <span className="px-2.5 py-0.5 rounded text-[11px] font-mono-tech font-bold uppercase bg-red-500/20 text-red-300 border border-red-500/40">
            CRITICAL PRIORITY
          </span>
        );
      case 'HIGH':
        return (
          <span className="px-2.5 py-0.5 rounded text-[11px] font-mono-tech font-bold uppercase bg-orange-500/20 text-orange-300 border border-orange-500/40">
            HIGH PRIORITY
          </span>
        );
      default:
        return (
          <span className="px-2.5 py-0.5 rounded text-[11px] font-mono-tech font-bold uppercase bg-cyan-500/20 text-cyan-300 border border-cyan-500/40">
            MEDIUM PRIORITY
          </span>
        );
    }
  };

  const getRecIcon = (iconName: string) => {
    switch (iconName) {
      case 'bolt':
        return <Zap className="w-5 h-5 text-orange-400" />;
      case 'alt_route':
        return <Navigation className="w-5 h-5 text-cyan-400" />;
      case 'local_hospital':
        return <Building className="w-5 h-5 text-red-400" />;
      case 'waves':
        return <Waves className="w-5 h-5 text-cyan-400" />;
      case 'cell_tower':
        return <Radio className="w-5 h-5 text-emerald-400" />;
      default:
        return <ShieldAlert className="w-5 h-5 text-orange-400" />;
    }
  };

  return (
    <div className="bg-[#171e37] rounded-2xl border border-[#212942] p-5 lg:p-6 shadow-xl flex flex-col gap-5">
      {/* Header */}
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-3 pb-3 border-b border-[#212942]">
        <div className="flex items-center gap-2.5">
          <div className="w-9 h-9 rounded-lg bg-orange-500/10 border border-orange-500/20 flex items-center justify-center text-orange-400">
            <Sparkles className="w-5 h-5" />
          </div>
          <div>
            <h2 className="font-display font-bold text-lg lg:text-xl text-white">
              AI-Generated Preparedness Recommendations
            </h2>
            <span className="text-xs text-slate-400">
              Actionable operational directives generated by Gemini model for incident command
            </span>
          </div>
        </div>

        <div className="flex items-center gap-2 text-xs font-mono-tech text-slate-400">
          <span className="text-emerald-400 font-bold">
            {Object.values(dispatchedIds).filter(Boolean).length} / {result.recommendations.length}
          </span>
          <span>DIRECTIVES DISPATCHED</span>
        </div>
      </div>

      {/* Actionable Cards Stack */}
      <div className="grid grid-cols-1 gap-3.5">
        {result.recommendations.map((rec) => {
          const isDispatched = !!dispatchedIds[rec.id];
          return (
            <div
              key={rec.id}
              className={`rounded-xl border p-4 sm:p-5 transition-all flex flex-col sm:flex-row sm:items-center justify-between gap-4 ${
                isDispatched
                  ? 'bg-[#131a33]/90 border-emerald-500/30'
                  : 'bg-[#0a122a] border-[#212942] hover:border-slate-600'
              }`}
            >
              {/* Left Details */}
              <div className="flex items-start gap-3.5 min-w-0">
                {/* Numeric index or Icon */}
                <div className="w-10 h-10 rounded-xl bg-[#171e37] border border-[#2c344d] flex items-center justify-center shrink-0 mt-0.5">
                  {getRecIcon(rec.icon)}
                </div>

                <div className="flex flex-col gap-1 min-w-0">
                  <div className="flex flex-wrap items-center gap-2">
                    <span className="font-mono-tech text-xs font-bold text-slate-400">
                      #{rec.id}
                    </span>
                    <h3 className="text-sm font-bold text-white tracking-wide">
                      {rec.title}
                    </h3>
                    {getPriorityBadge(rec.priority)}
                    {rec.timeframe && (
                      <span className="text-[11px] font-mono-tech text-slate-400 flex items-center gap-1">
                        <Clock className="w-3 h-3 text-slate-500" />
                        {rec.timeframe}
                      </span>
                    )}
                  </div>

                  <p className="text-sm text-slate-200 leading-relaxed">
                    {rec.action}
                  </p>
                </div>
              </div>

              {/* Right Action: Dispatch Toggle */}
              <div className="flex items-center gap-2 shrink-0 self-end sm:self-center pl-13 sm:pl-0">
                <button
                  type="button"
                  onClick={() => toggleDispatch(rec.id)}
                  className={`px-3.5 py-2 rounded-lg text-xs font-mono-tech font-bold flex items-center gap-1.5 transition-all ${
                    isDispatched
                      ? 'bg-emerald-500/20 text-emerald-300 border border-emerald-500/40 hover:bg-emerald-500/30'
                      : 'bg-orange-500 hover:bg-orange-600 text-white shadow-md shadow-orange-500/20'
                  }`}
                >
                  {isDispatched ? (
                    <>
                      <Check className="w-4 h-4 text-emerald-400" />
                      <span>Dispatched</span>
                    </>
                  ) : (
                    <>
                      <Send className="w-3.5 h-3.5" />
                      <span>Dispatch Directive</span>
                    </>
                  )}
                </button>
              </div>
            </div>
          );
        })}
      </div>
    </div>
  );
};
